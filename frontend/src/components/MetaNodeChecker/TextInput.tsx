import * as React from 'react';

// A text input that doesn't let key presses reach the page's global handlers.
export function TextInput({
  value,
  onChange,
  placeholder,
}: {
  value: string;
  onChange: (value: string) => void;
  placeholder: string;
}) {
  return (
    <input
      type="text"
      placeholder={placeholder}
      value={value}
      onChange={(ev) => onChange(ev.currentTarget.value)}
      // Don't let the global TAB handler (chain switching) swallow input
      onKeyDown={(ev) => ev.stopPropagation()}
    />
  );
}
